import { readFile, writeFile } from 'node:fs/promises'
const root = new URL('../', import.meta.url)
const read = name => readFile(new URL(name, root), 'utf8')
const tank = (await read('src/tank.js')).replace(/^export /gm, '')
const windowGeometry = (await read('src/window.js')).replace(/^export /gm, '')
const flight = (await read('src/flight.js')).replace(/^export /gm, '')
const flightSave = (await read('src/flight-save.js')).replace(/^export /gm, '')
const missionGame = (await read('src/mission-game.js')).replace(/^import .*\r?\n/gm, '').replace(/^export /gm, '')
const groundMission = (await read('src/ground-mission.js')).replace(/^import .*\r?\n/gm, '').replace(/^export /gm, '')
const engine = (await read('src/engine.js')).replace(/^import .*\r?\n/gm, '').replace(/^export /gm, '')
const ui = await read('src/ui.js')
const terrain = (await read('src/escort-terrain.js')).replace(/^export /gm, '')
const art = (await read('src/escort-art.js')).replace(/^export /gm, '')
const taskView = (await read('src/escort-task.js')).replace(/^import .*\r?\n/gm, '').replace(/^export /gm, '')
const expedition = terrain + '\n' + art + '\n' + taskView + '\n' + (await read('src/escort-action.js')).replace(/^import .*\r?\n/gm, '').replace(/^export /gm, '')
const expeditionUI = (await read('src/escort-live.js')).replace(/^export /gm, '') + '\n' + await read('src/escort-action-ui.js')
const css = await read('src/arcade.css') + '\n' + await read('src/expedition.css')
await writeFile(new URL('client.js', root), `// Generated by npm run build. Edit src/ instead.\nwindow.__ModuleLoader__.load({\n  id: 'dsh-whileplay',\n  factory(require) {\n${tank}\n${flight}\n${flightSave}\n${missionGame}\n${groundMission}\n${engine}\n${windowGeometry}\n${expedition}\n${expeditionUI}\nconst arcadeCSS = ${JSON.stringify(css)}\n${ui}\n  },\n})\n`)
