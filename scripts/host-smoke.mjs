// Optional real-host smoke: reuses a source checkout's installed Playwright.
import { spawn } from 'node:child_process'
import { createRequire } from 'node:module'
import { mkdir, mkdtemp, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import assert from 'node:assert/strict'
const root = resolve(import.meta.dirname, '..')
if (!process.env.DSH_SOURCE_ROOT) throw new Error('Set DSH_SOURCE_ROOT to a prepared DeepSeek Harness source checkout before running test:host.')
const harness = resolve(process.env.DSH_SOURCE_ROOT)
const require = createRequire(resolve(harness, 'apps/web/package.json'))
const { chromium } = require('playwright')
await mkdir(resolve(root, '.runtime'), { recursive: true })
const smokeHome = await mkdtemp(resolve(root, '.runtime/host-smoke-'))
const overlay = resolve(root, '.runtime/smoke.patch.yml')
await writeFile(overlay, `- insert:\n    - id: whileplay\n      name: '${pathToFileURL(resolve(root, 'index.js')).href}'\n`)
const child = spawn(process.execPath, ['--import', 'tsx/esm', 'apps/cli/src/bin.ts', 'web', '--patch', overlay, '--patch', 'apps/web/tests/pin-browse-picker.overlay.yml', '--no-open', '--port', '0'], {
  cwd: harness, env: { ...process.env, DSH_HOME: smokeHome }, stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true,
})
let browser
try {
  const url = await new Promise((accept, reject) => {
    let output = ''
    const timeout = setTimeout(() => reject(new Error('Harness startup timed out')), 120000)
    child.once('exit', code => { clearTimeout(timeout); reject(new Error(`Harness exited: ${code}`)) })
    for (const stream of [child.stdout, child.stderr]) stream.on('data', chunk => {
      output += chunk
      const match = output.match(/dsh web: (http:\/\/\S+)/)
      if (match) { clearTimeout(timeout); accept(match[1]) }
    })
  })
  const channel = process.env.WHILEPLAY_BROWSER_CHANNEL || (process.platform === 'win32' ? 'msedge' : undefined)
  browser = await chromium.launch({ channel, headless: true })
  const page = await browser.newPage({ locale: 'zh-CN', viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(url)
  await page.locator('.arcade-launch').waitFor()
  // Every run has a fresh home: wait for each onboarding transition explicitly.
  await page.getByRole('button', { name: '继续', exact: true }).click()
  const onboarding = page.getByRole('dialog', { name: '开始使用', exact: true })
  await onboarding.waitFor({ state: 'visible' })
  await onboarding.getByRole('button', { name: '关闭', exact: true }).click()
  await onboarding.waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: '玩一小局' }).click()
  const panel = page.getByRole('region', { name: '玩一小局', exact: true })
  await panel.waitFor()
  const canvas = panel.locator('canvas')
  assert.equal(await canvas.getAttribute('width'), '320')
  assert.equal(await canvas.getAttribute('height'), '480')
  const initialBounds = await canvas.boundingBox()
  assert.ok(initialBounds.height > initialBounds.width)
  await panel.getByRole('button', { name: '开始游戏', exact: true }).click()
  assert.equal(await canvas.evaluate(el => el === document.activeElement), true)
  await page.keyboard.down('ArrowRight')
  await page.waitForTimeout(180)
  await page.keyboard.up('ArrowRight')
  await panel.getByRole('button', { name: '暂停', exact: true }).click()
  const pausedImage = await canvas.evaluate(el => el.toDataURL())
  await page.waitForTimeout(120)
  assert.equal(await canvas.evaluate(el => el.toDataURL()), pausedImage)
  const search = panel.getByRole('searchbox', { name: '搜索游戏' })
  await search.fill('贪吃')
  assert.equal(await panel.locator('.arcade-game-list button').count(), 1)
  await search.fill('no-such-game')
  assert.match(await panel.locator('.arcade-empty').textContent(), /没有找到/)
  await search.fill('')
  await panel.getByRole('button', { name: '飞行', exact: true }).click()
  assert.equal(await panel.locator('.arcade-game-list button').count(), 1)
  await panel.getByRole('button', { name: '全部', exact: true }).click()
  const fullBounds = await panel.boundingBox()
  await panel.getByRole('button', { name: '极简模式', exact: true }).click()
  assert.equal(await panel.locator('.arcade-library').isVisible(), false)
  assert.equal(await panel.locator('.arcade-scores').isVisible(), false)
  const compactBounds = await panel.boundingBox()
  assert.ok(compactBounds.width < fullBounds.width)
  assert.ok(Math.abs((compactBounds.width - 2) / (compactBounds.height - 2) - 2 / 3) < 0.01)
  await panel.getByRole('button', { name: '移动窗口', exact: true }).press('ArrowLeft')
  assert.ok((await panel.boundingBox()).x < compactBounds.x)
  await panel.getByRole('button', { name: '调整窗口大小：右下角', exact: true }).press('ArrowRight')
  assert.ok((await panel.boundingBox()).width > compactBounds.width)
  await panel.getByRole('button', { name: '完整模式', exact: true }).click()
  const restoredBounds = await panel.boundingBox()
  assert.equal(restoredBounds.width, fullBounds.width)
  assert.equal(restoredBounds.height, fullBounds.height)
  for (const game of ['贪吃蛇', '坦克大战']) {
    await panel.getByRole('button', { name: game, exact: true }).click()
    await panel.getByRole('button', { name: '开始游戏', exact: true }).click()
    await page.keyboard.press('ArrowRight')
    await page.keyboard.press('Space')
    await panel.getByRole('button', { name: '暂停', exact: true }).click()
  }
  await panel.getByRole('button', { name: '收起', exact: true }).click()
  assert.equal(await panel.count(), 0)
  await page.getByRole('button', { name: '玩一小局' }).click()
  assert.equal(await panel.getByRole('button', { name: '坦克大战', exact: true }).getAttribute('aria-pressed'), 'true')
  assert.equal(await canvas.getAttribute('width'), '416')
  assert.equal(await canvas.getAttribute('height'), '416')
  await mkdir(resolve(root, 'artifacts'), { recursive: true })
  for (const [label, slug] of [['坦克大战', 'tank'], ['贪吃蛇', 'snake']]) {
    await panel.getByRole('button', { name: label, exact: true }).click()
    await panel.getByRole('button', { name: '联动演练', exact: true }).click()
    await page.waitForTimeout(1200)
    assert.match(await panel.locator('.arcade-escort-info').textContent(), /模拟工具调用与 Step 补给/)
    await panel.getByRole('button', { name: '暂停', exact: true }).click()
    await page.screenshot({ path: resolve(root, `artifacts/whileplay-${slug}-mission.png`) })
  }
  await panel.getByRole('button', { name: '飞机大战', exact: true }).click()
  await page.screenshot({ path: resolve(root, 'artifacts/arcade.png') })
  const lightBackground = await panel.evaluate(el => getComputedStyle(el).backgroundColor)
  const lightCanvas = await canvas.evaluate(el => el.toDataURL())
  await page.evaluate(() => document.body.setAttribute('data-ds-dark-theme', ''))
  await page.waitForTimeout(100)
  assert.notEqual(await panel.evaluate(el => getComputedStyle(el).backgroundColor), lightBackground)
  assert.notEqual(await canvas.evaluate(el => el.toDataURL()), lightCanvas)
  await page.screenshot({ path: resolve(root, 'artifacts/arcade-dark.png') })
  await page.evaluate(() => document.body.removeAttribute('data-ds-dark-theme'))
  // Stress the layout with extra DOM rows only; these are not playable games.
  const playBounds = await panel.locator('.arcade-play').boundingBox()
  const catalogStress = await panel.locator('.arcade-game-list').evaluate(el => {
    for (let i = 0; i < 30; i++) { const row = el.firstElementChild.cloneNode(true); row.dataset.stress = ''; el.append(row) }
    return { scroll: el.scrollHeight, client: el.clientHeight }
  })
  assert.ok(catalogStress.scroll > catalogStress.client)
  assert.deepEqual(await panel.locator('.arcade-play').boundingBox(), playBounds)
  await panel.locator('[data-stress]').evaluateAll(rows => rows.forEach(row => row.remove()))
  await page.setViewportSize({ width: 390, height: 844 })
  await page.waitForFunction(() => {
    const bounds = document.querySelector('.arcade-panel').getBoundingClientRect()
    return bounds.x >= 0 && bounds.y >= 0 && bounds.right <= innerWidth && bounds.bottom <= innerHeight
  })
  const bounds = await panel.boundingBox()
  assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 391)
  assert.ok(bounds.y >= 0 && bounds.y + bounds.height <= 844)
  await page.screenshot({ path: resolve(root, 'artifacts/arcade-mobile.png') })
  await panel.getByRole('button', { name: '游戏库' }).click()
  await panel.getByRole('button', { name: '贪吃蛇', exact: true }).click()
  assert.equal(await panel.locator('.arcade-library').isVisible(), false)
  assert.equal(await canvas.getAttribute('width'), '480')
  await page.setViewportSize({ width: 1440, height: 1000 })
  const selectGame = async name => {
    const button = panel.getByRole('button', { name, exact: true })
    if (!await button.isVisible()) await panel.getByRole('button', { name: '游戏库' }).click()
    await button.click()
  }
  await selectGame('飞机大战')
  await panel.getByRole('button', { name: '联动演练', exact: true }).click()
  const choices = panel.getByRole('group', { name: '二选一升级', exact: true })
  await choices.waitFor({ state: 'visible' })
  assert.equal(await choices.getByRole('button').count(), 2)
  await choices.getByRole('button').first().click()
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('dsh-whileplay.flights.v1')).rows[0].game.flight.upgrades.fire === 1)
  await panel.getByRole('button', { name: '暂停', exact: true }).click()
  const checkpoint = await page.evaluate(() => JSON.parse(localStorage.getItem('dsh-whileplay.flights.v1')).rows[0].game)
  assert.ok(checkpoint.time >= 1)
  await selectGame('坦克大战')
  await selectGame('飞机大战')
  assert.equal(await panel.getByRole('button', { name: '继续', exact: true }).count(), 2)
  await page.reload()
  await onboarding.waitFor({ state: 'visible' })
  await onboarding.getByRole('button', { name: '关闭', exact: true }).click()
  await onboarding.waitFor({ state: 'hidden' })
  await page.locator('.arcade-launch').click()
  assert.match(await panel.locator('.arcade-status').textContent(), /已恢复飞机存档/)
  const afterReload = await page.evaluate(() => JSON.parse(localStorage.getItem('dsh-whileplay.flights.v1')).rows[0].game)
  assert.equal(afterReload.time, checkpoint.time)
  assert.equal(afterReload.flight.upgrades.fire, 1)
  assert.equal(afterReload.escort.demo, true)
  await panel.getByRole('button', { name: '继续', exact: true }).first().click()
  await page.waitForFunction(time => JSON.parse(localStorage.getItem('dsh-whileplay.flights.v1')).rows[0].game.time > time + .1, checkpoint.time)
  await panel.getByRole('button', { name: '暂停', exact: true }).click()
  await page.screenshot({ path: resolve(root, 'artifacts/whileplay-flight-upgrades.png') })
  await selectGame('小队护送远征')
  let expedition = page.getByRole('region', { name: '小队护送远征', exact: true })
  assert.equal(await expedition.getByRole('button', { name: '当前会话', exact: true }).getAttribute('aria-pressed'), 'true')
  assert.ok(!(await expedition.locator('.exp-action-sidebar').textContent()).includes('番茄钟小站'))
  await page.screenshot({ path: resolve(root, 'artifacts/whileplay-escort-live-empty.png') })
  await expedition.getByRole('button', { name: '联动演练', exact: true }).click()
  const beforeDrag = await expedition.boundingBox()
  await page.mouse.move(beforeDrag.x + 40, beforeDrag.y + 25)
  await page.mouse.down(); await page.mouse.move(beforeDrag.x + 60, beforeDrag.y + 40); await page.mouse.up()
  assert.ok((await expedition.boundingBox()).x > beforeDrag.x, 'expedition window can be moved')
  await page.screenshot({ path: resolve(root, 'artifacts/whileplay-expedition.png') })
  await expedition.getByRole('button', { name: '开始实时演练', exact: true }).click()
  const battle = expedition.locator('canvas')
  const skillBounds = await expedition.getByRole('button', { name: /Q · 工程修复/ }).boundingBox()
  const footerBounds = await expedition.locator('.exp-footer').boundingBox()
  assert.ok(skillBounds.y + skillBounds.height <= footerBounds.y, 'portrait controls stay visible above the footer')
  assert.equal(await battle.getAttribute('width'), '480')
  assert.equal(await battle.getAttribute('height'), '720')
  await page.keyboard.down('KeyD'); await page.waitForTimeout(250); await page.keyboard.up('KeyD')
  await page.keyboard.press('Space')
  await page.keyboard.press('KeyQ')
  await page.waitForFunction(() => Object.keys(localStorage).some(key => key.startsWith('dsh-whileplay.escort-action.v2:') && JSON.parse(localStorage.getItem(key)).used === 1))
  await page.waitForFunction(() => Object.keys(localStorage).some(key => key.startsWith('dsh-whileplay.escort-action.v2:') && JSON.parse(localStorage.getItem(key)).dashCooldown > 0))
  await page.waitForTimeout(5200)
  await page.screenshot({ path: resolve(root, 'artifacts/whileplay-escort-task-tools.png') })
  assert.match(await expedition.locator('.exp-action-sidebar').textContent(), /雷达岛/)
  // Drive the battle through actual pointer input instead of waiting motionless under fire.
  const arena = await battle.boundingBox()
  await page.mouse.move(arena.x + arena.width * .25, arena.y + arena.height * .5); await page.mouse.down()
  let driven
  let photographedWing = false
  for (let n = 0; n < 300; n++) {
    driven = await page.evaluate(() => JSON.parse(localStorage.getItem(Object.keys(localStorage).find(k => k.startsWith('dsh-whileplay.escort-action.v2:')))))
    if (driven.phase === 'attention') {
      await page.mouse.up()
      await expedition.getByRole('button', { name: '模拟拒绝', exact: true }).click()
      await expedition.locator('.exp-action-curtain').getByRole('button', { name: '继续护航', exact: true }).click()
      await page.mouse.move(arena.x + arena.width / 2, arena.y + arena.height * .7); await page.mouse.down()
      continue
    }
    if (driven.time >= 19 && !photographedWing) { await page.screenshot({ path: resolve(root, 'artifacts/whileplay-escort-task-agent.png') }); photographedWing = true }
    if (driven.time >= 38 || driven.phase !== 'playing') break
    const drop = driven.drops.find(d => d.type === 'salvage')
    const x = drop ? drop.x : driven.convoy.x + Math.sin(driven.time * 1.8) * 100
    const y = drop ? drop.y + 10 : driven.convoy.y + 65 + Math.cos(driven.time * 1.4) * 40
    await page.mouse.move(arena.x + Math.max(18, Math.min(462, x)) / 480 * arena.width, arena.y + Math.max(110, Math.min(640, y)) / 720 * arena.height)
    if (driven.shots.some(b => Math.hypot(b.x - driven.player.x, b.y - driven.player.y) < 70)) await page.keyboard.press('Space')
    if (driven.convoy.hp < 75 && driven.repair) await page.keyboard.press('KeyQ')
    if (driven.enemies.length >= 6 && driven.strike) await page.keyboard.press('KeyE')
    await page.waitForTimeout(300)
  }
  await page.mouse.up()
  assert.ok(driven.time >= 38, `battle stopped before flagship: ${JSON.stringify({ phase: driven.phase, time: driven.time, hp: driven.player.hp })}`)
  await page.screenshot({ path: resolve(root, 'artifacts/whileplay-escort-task-cargo.png') })
  await expedition.getByRole('button', { name: '暂停护航', exact: true }).click()
  const actionKey = await page.evaluate(() => Object.keys(localStorage).find(key => key.startsWith('dsh-whileplay.escort-action.v2:')))
  const actionSaved = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), actionKey)
  assert.ok(actionSaved.player.x !== 240); assert.ok(actionSaved.used >= 1); assert.ok(actionSaved.seen.includes('flagship-1')); assert.deepEqual(actionSaved.cargo, ['pomodoro.html']); assert.equal(actionSaved.wings, 2)
  await page.reload()
  await onboarding.waitFor({ state: 'visible' }); await onboarding.getByRole('button', { name: '关闭', exact: true }).click(); await onboarding.waitFor({ state: 'hidden' })
  await page.locator('.arcade-launch').click(); await selectGame('小队护送远征')
  expedition = page.getByRole('region', { name: '小队护送远征', exact: true })
  await expedition.getByRole('button', { name: '联动演练', exact: true }).click()
  await expedition.locator('.exp-action-curtain').waitFor({ state: 'visible' })
  assert.equal(await page.evaluate(key => JSON.parse(localStorage.getItem(key)).time, actionKey), actionSaved.time)
  await page.setViewportSize({ width: 390, height: 844 })
  const expeditionBounds = await expedition.boundingBox()
  assert.ok(expeditionBounds.x >= 0 && expeditionBounds.x + expeditionBounds.width <= 391)
  await page.screenshot({ path: resolve(root, 'artifacts/whileplay-escort-action-mobile.png') })
  await expedition.getByRole('button', { name: '返回游戏库', exact: true }).click()
  await panel.waitFor({ state: 'visible' })
  assert.deepEqual(errors, [])
  console.log('Real Harness smoke passed: classic games, plane upgrades/checkpoints, real-time escort movement, shooting, dash, Q skill, flagship, reload and mobile; no page errors.')
} finally {
  if (browser) await browser.close()
  child.kill()
}
